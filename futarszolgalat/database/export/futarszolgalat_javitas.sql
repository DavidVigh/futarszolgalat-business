CREATE VIEW v_elerheto_futarok AS
SELECT f.id, f.nev, f.telszam, f.jarmu, f.hatosugar_km,
       fp.gps_x, fp.gps_y, fp.cim
FROM futar f
LEFT JOIN futar_pozicio fp ON f.id = fp.futarID
