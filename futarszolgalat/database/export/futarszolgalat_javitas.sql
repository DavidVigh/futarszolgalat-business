CREATE VIEW v_futar_poziciok AS
SELECT f.id AS futar_id, f.nev AS futar, f.jarmu, f.allapot, f.hatosugar_km,
       fp.gps_x, fp.gps_y, fp.cim AS aktualis_cim, fp.frissitve
FROM futar f
